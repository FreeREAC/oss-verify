"""Write the table of projects in README.md from projects/*/project.yaml.

    tools/projects_table.py           rewrite the table between its markers in README.md
    tools/projects_table.py --check   exit 1 if README.md's table is not what this would write

The table is generated: edit project.yaml files, not README.md. Requires PyYAML, as tools/validate.py does.
"""
import argparse
import pathlib
import sys

import validate

README = pathlib.Path(__file__).resolve().parent.parent / "README.md"
BEGIN = "<!-- BEGIN projects table: generated by tools/projects_table.py from projects/*/project.yaml; do not edit -->"
END = "<!-- END projects table -->"


def cell(text):
    """Text from a project.yaml for a Markdown table cell: no pipes, backticks or line breaks."""
    return validate.printable(str(text)).replace("|", "\\|").replace("`", "'")


def rows(projects=validate.PROJECTS):
    """One row per valid project under `projects`, in name order."""
    lines = []
    for directory in sorted(path for path in projects.glob("*") if path.is_dir() and not path.is_symlink()):
        problems, _, _ = validate.check_project(directory)
        if problems:
            continue
        config = validate.load(directory)
        repo, _, ref = config["repo"].partition("#")
        targets = ", ".join(config["fuzz_targets"]) if config.get("fuzz_targets") else "all"
        if (directory / "Dockerfile").is_file():
            files = "here"
        elif config.get("dockerfile"):
            files = "in its repository"
        else:
            files = "not yet"
        enrolled = "seeded by us; provisional" if config["primary_contact"] == validate.NO_CONTACT else "its maintainers"
        state = " (disabled)" if config.get("disabled") else ""
        lines.append(
            f"| [{cell(directory.name)}](projects/{directory.name}/){state} | {cell(repo)} | {cell(ref or 'default branch')} "
            f"| {cell(targets)} | {files} | {enrolled} |"
        )
    return lines


def table(projects=validate.PROJECTS):
    """The generated table, with its markers."""
    body = rows(projects)
    head = ["| project | repository | ref | fuzz targets | build files | enrolled by |", "|---|---|---|---|---|---|"]
    if not body:
        head = ["No project is enrolled yet."]
        return "\n".join([BEGIN, *head, END])
    return "\n".join([BEGIN, *head, *body, END])


def render(text, projects=validate.PROJECTS):
    """README.md's text with its table replaced by the one for `projects`. Raise ValueError if the markers are
    missing."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"README.md has no table markers ({BEGIN} ... {END})")
    return text[:start] + table(projects) + text[end + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that README.md is up to date")
    options = parser.parse_args()
    text = README.read_text(encoding="utf-8")
    try:
        wanted = render(text)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    if options.check:
        if wanted != text:
            print("README.md's projects table is out of date: run tools/projects_table.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
