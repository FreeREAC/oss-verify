"""Port a project's build from the build recipe of oss-fuzz-theorems release 2026.10.0-rc.2.

    tools/port.py --from CHECKOUT --recipe RECIPE --assets ASSETS --out DIR NAME ...

CHECKOUT is a checkout of oss-fuzz-theorems at that release, RECIPE its build recipe (recipe.tar.zst) unpacked, and
ASSETS a directory with the release's <name>-src.MANIFEST.tsv files, which say where each source tree of a project
goes. For each NAME, this writes DIR/NAME/: the Dockerfile, build.sh and sources file of the project's build, the
files of the release's own a build reads (shims, copies of harnesses), and its build-only patches with their series.
tools/seed.py writes the project.yaml beside them.

The build is the release's, target by target: build.sh runs each target's pin (its build_lib and helpers) through
infra/base-builder's release-target.sh, at the paths the release's binaries record. Nothing is re-derived: the pins
are copied, with the release build's internal paths replaced by this builder's.

A project is ported only if every fuzz target project.yaml lists can be. One that cannot is refused with the reason
(for example a source tree of a kind this does not lay out yet); the report says which.

Exit codes: 0 if every NAME was ported; 1 otherwise.
"""
import argparse
import json
import os
import pathlib
import re
import sys

import seed
import validate

GENERATED = "Generated by tools/port.py from the build recipe of oss-fuzz-theorems 2026.10.0-rc.2; do not edit."
# Lines of a pin that a port does not keep: the tree it names comes from the Dockerfile, and recipes.sh is sourced by
# release-target.sh.
DROPPED = re.compile(r"^(URL|COMMIT|BUILD_IMAGE)=|^\. /work/tools/ossfuzz/recipes\.sh\s*$")
GITHUB = re.compile(r"https://github\.com/([\w.-]+)/([\w.-]+?)(?:\.git)?/?")
DELIMITER = "OV_PIN_END"


class Unsupported(Exception):
    """A build this tool cannot port yet. The message says why."""


def read_tsv(path):
    """The rows of a tab-separated file with a header row, skipping # comments, as dictionaries."""
    lines = [line.rstrip("\n").split("\t") for line in path.read_text(encoding="utf-8").splitlines()
             if line and not line.startswith("#")]
    head, rows = lines[0], lines[1:]
    return [dict(zip(head, row)) for row in rows]


class Release:
    """The parts of the release a port reads: its checkout, its recipe and its source manifests."""

    def __init__(self, checkout, recipe, assets):
        self.checkout, self.recipe, self.assets = checkout, recipe, assets
        self.patches, self.harnesses = seed.load_recipe(recipe)
        self.series = read_tsv(recipe / "patches" / "series.tsv")
        self.upstream = {}
        for line in (recipe / "MANIFEST.tsv").read_text(encoding="utf-8").splitlines()[1:]:
            path, sha256, size, mode, kind, why = line.split("\t", 5)
            if kind == "upstream":
                self.upstream[path] = (sha256, why)

    def pin(self, target):
        path = self.recipe / "targets" / target / "pin"
        if not path.is_file():
            raise Unsupported(f"the recipe has no pin for {target}")
        return path.read_text(encoding="utf-8")

    def manifest(self, name):
        path = self.assets / f"{name}-src.MANIFEST.tsv"
        if not path.is_file():
            raise Unsupported(f"no {path.name} among the assets")
        return read_tsv(path)


def target_files(release, target):
    """The files of the release's own in the target's recipe directory, other than its pin and plugin, at any depth:
    {path relative to that directory: path}. Upstream files the build reads there are not in the recipe;
    recipe_files() finds those."""
    directory = release.recipe / "targets" / target
    files = {}
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory).as_posix()
        if relative in ("pin", "plugin.c") or (path.is_dir() and not path.is_symlink()):
            continue
        if path.is_symlink() or not path.is_file():
            raise Unsupported(f"{target}: the recipe has a link or special file of its own ({relative})")
        files[relative] = path
    return files


def recipe_files(release, target):
    """The upstream files the release put in the target's recipe directory: [(name, url, sha256)]."""
    found = []
    prefix = f"targets/{target}/"
    for path, (sha256, why) in sorted(release.upstream.items()):
        if not path.startswith(prefix):
            continue
        name = path[len(prefix):]
        if "/" in name:
            raise Unsupported(f"{target}: an upstream file in a subdirectory of the recipe ({name})")
        match = re.match(r"src-asset git (\S+) ([0-9a-f]{40}) (\S+) [0-9a-f]{40}", why)
        github = GITHUB.fullmatch(match.group(1)) if match else None
        if not github:
            raise Unsupported(f"{target}: the upstream file {name} is not from a GitHub repository")
        owner, repo = github.groups()
        url = f"https://raw.githubusercontent.com/{owner}/{repo}/{match.group(2)}/{match.group(3)}"
        found.append((name, url, sha256))
    return found


def pin_body(release, target):
    """A target's pin as build.sh runs it, and the targets it DEPENDS on. The pin is the release's, less the lines
    that name its tree and source recipes.sh: its paths are the release layout's, which release-target.sh sets up."""
    text = release.pin(target)
    depends = re.search(r'^DEPENDS="([^"]*)"', text, re.M)
    lines = [line for line in text.splitlines() if not DROPPED.search(line)]
    body = "\n".join(lines)
    if DELIMITER in body:
        raise Unsupported(f"{target}: its pin holds the line {DELIMITER}")
    return body.strip("\n") + "\n", (depends.group(1).split() if depends else [])


def patches_for(release, tree, targets):
    """The release's patches for a source tree, in order, and the targets each applies to."""
    found = []
    for row in release.series:
        if row["series"].lower() == tree:
            applies = [target for target in row.get("targets", "").split(",") if target in targets]
            if applies:
                found.append((row["series"], row["patch"], applies))
    return found


def map_targets(name, seeded, release):
    """The release's build target of each fuzz target project.yaml lists: [(fuzz target, release target)]."""
    mapped = []
    for harness in seeded.targets:
        details = seed.read_yaml(release.checkout / "projects" / name / harness / "harness.yaml")
        target = seed.target_of(name, harness, seed.harness_source(details), release.harnesses)
        if target is None:
            raise Unsupported(f"{harness}: cannot tell which of the recipe's targets builds it")
        mapped.append((harness, target))
    return mapped


def placement(where, target):
    """The path of a placement under ext/<target>/, or Unsupported."""
    prefix = f"ext/{target}/"
    if not where.startswith(prefix) or ".." in where.split("/"):
        raise Unsupported(f"{target}: the release laid a tree out at {where}")
    return where[len(prefix):]


def https(url, what):
    if not url.startswith("https://"):
        raise Unsupported(f"{what} is fetched from {url}, not over https")
    return url


def layouts(name, seeded, rows, order):
    """For each release target, how its tree is laid out: (main, items), where main is the directive that makes
    ext/<target>/src and items are (path under ext/<target>/, directive fields) for everything else placed there."""
    main, items = {}, {target: [] for target in order}
    for row in rows:
        detail = json.loads(row.get("detail") or "{}")
        materialise = detail.get("materialise", [])
        placed = {}
        for pin in row.get("pins", "").split(","):
            target, _, where = pin.partition("=")
            if target in order:
                placed[target] = where
        kind = row["kind"]
        if kind == "gitlink" or (kind == "git-subtree" and set(materialise) <= {"provenance", "recipe-file"}):
            continue  # a submodule's commit (its tree is a row of its own), or OSS-Fuzz's directory
        if kind == "git" and row["id"] == seeded.commit and materialise == ["checkout"]:
            for target, where in placed.items():
                if placement(where, target) != "src":
                    raise Unsupported(f"{target}: the release laid its tree out at {where}")
                main[target] = ("tree", f"upstream/{name}")
            continue
        if kind == "git" and materialise in (["checkout"], ["git-archive"]):
            url = https(row["source"], f"the tree at {row['id'][:12]}")
            for target, where in placed.items():
                extra = ("archive",) if materialise == ["git-archive"] else ()
                items[target].append((placement(where, target), ("git", url, row["id"], *extra)))
            continue
        if kind == "vendor-file":
            url = https(row["source"], "a vendored file")
            for target, where in placed.items():
                items[target].append((placement(where, target), ("file", url, row["id"].removeprefix("sha256:"))))
            continue
        if kind in ("vendor-tree", "tarball"):
            url = https(row["source"], f"a {kind}")
            digest = row["id"].removeprefix("sha256:")
            for key, how in detail.get("placements", {}).items():
                target, _, kept = key.partition("=")
                if target not in order:
                    continue
                items[target].append((placement(kept, target), ("file", url, digest)))
                if kind == "tarball":
                    if not str(how.get("unpack", "")).startswith("src (one top directory stripped"):
                        raise Unsupported(f"{target}: the release unpacked {url} as {how.get('unpack')}")
                    main[target] = ("archive", url, digest, "1")
                else:
                    items[target].append((placement(how["members_to"], target),
                                          ("archive", url, digest, str(how.get("strip", 1)), *how.get("select", []))))
            continue
        raise Unsupported(f"a source tree of kind {kind} ({', '.join(materialise) or 'no materialise'}) "
                          "is not laid out by this tool yet")
    missing = [target for target in order if target not in main]
    if missing:
        raise Unsupported(f"no source tree in the manifest for {', '.join(missing)}")
    return main, items


def plan(name, release):
    """Everything the port of one project writes: ({file name: text or bytes}, {names of executable files})."""
    seeded = seed.assess(name, release.checkout, (release.patches, release.harnesses))
    if seeded.reason:
        raise Unsupported(f"not seedable: {seeded.reason}")
    mapped = map_targets(name, seeded, release)
    order, dependencies = [], {}
    for _, target in mapped:
        _, depends = pin_body(release, target)
        dependencies[target] = depends
        for needed in [*depends, target]:
            if needed not in order:
                order.append(needed)

    main, items = layouts(name, seeded, release.manifest(name), order)
    tree_id = seed.series_of(seeded.repo, seeded.commit)
    patched = {target: tuple(patch for _, patch, applies in patches_for(release, tree_id, order) if target in applies)
               for target in order}
    for target in order:
        for path, directive in items[target]:
            if directive[0] == "git" and patches_for(release, seed.series_of(directive[1], directive[2]), [target]):
                raise Unsupported(f"{target}: the release patched a tree other than the project's own")

    # Targets whose trees are laid out alike share the first one's; the others get trees of their own.
    sources, files, series = [], {}, []
    shared = {}
    for target in order:
        inside = tuple(sorted((path, directive) for path, directive in items[target] if path.split("/")[0] == "src"))
        key = (main[target], inside, patched[target])
        if key in shared:
            sources.append(f"link\text/{target}/src\text/{shared[key]}/src")
        else:
            shared[key] = target
            kind, *rest = main[target]
            sources.append("\t".join([kind, f"ext/{target}/src", *rest]) if kind == "tree"
                           else "\t".join(["archive", f"ext/{target}/src", *rest]))
            for path, directive in inside:
                sources.append("\t".join([directive[0], f"ext/{target}/{path}", *directive[1:]]))
            for patch in patched[target]:
                text = (release.recipe / "patches" / tree_id_dir(release, tree_id) / patch).read_bytes()
                stored = f"{target}.{patch}" if len(shared) > 1 or len(order) > 1 else patch
                files[stored] = text
                series.append(stored)
                sources.append(f"patch\text/{target}/src\t{stored}")
        for path, directive in sorted(items[target]):
            if path.split("/")[0] != "src":
                sources.append("\t".join([directive[0], f"ext/{target}/{path}", *directive[1:]]))
    executable = set()
    for target in order:
        for file_name, path in target_files(release, target).items():
            # A project directory is flat: a file in a subdirectory of the recipe's is stored under a dotted name.
            stored = f"{target}.{file_name.replace('/', '.')}"
            if not validate.FILE_NAME.fullmatch(stored) or stored in files:
                raise Unsupported(f"{target}: its file {file_name} cannot be stored as {stored}")
            files[stored] = path.read_bytes()
            if os.access(path, os.X_OK):
                executable.add(stored)
            sources.append(f"copy\ttargets/{target}/{file_name}\t{stored}")
        for file_name, url, sha256 in recipe_files(release, target):
            sources.append(f"file\ttargets/{target}/{file_name}\t{url}\t{sha256}")
    if series:
        files["series"] = "".join(f"{patch}\n" for patch in series)
    files["sources"] = (f"# {GENERATED}\n# kind\tpath\targuments: see lay-out-sources\n" + "\n".join(sources) + "\n")
    files["Dockerfile"] = dockerfile(name)
    files["build.sh"] = build_script(name, mapped, dependencies, release)
    executable.add("build.sh")
    return files, executable


def tree_id_dir(release, tree_id):
    """The directory of the recipe's patches for a tree, in the recipe's own spelling."""
    for row in release.series:
        if row["series"].lower() == tree_id:
            return row["series"]
    raise Unsupported(f"no patches for {tree_id}")


def dockerfile(name):
    return f"""# {GENERATED}
#
# {name} on the OSS Verifier builder, laid out as the release built it (lay-out-sources reads the sources file).
# tools/check passes REPO, COMMIT and BASE_BUILDER.
ARG BASE_BUILDER=oss-verifier-base-builder
FROM ${{BASE_BUILDER}}
ARG REPO
ARG COMMIT
RUN fetch-commit $SRC/upstream/{name}
COPY . $SRC/project/
RUN lay-out-sources $SRC/project/sources $WORK && cp $SRC/project/build.sh $SRC/build.sh
WORKDIR $SRC
"""


def build_script(name, mapped, dependencies, release):
    blocks = []
    for harness, target in mapped:
        body, _ = pin_body(release, target)
        begin = " ".join(["ov_target_begin", target, *dependencies[target]])
        lines = [f"# {harness}: the release's target {target}", "(", begin]
        if re.search(r"\$\{?COMMIT\b", body):
            lines.append(f'COMMIT=$(git -C "$SRC/upstream/{name}" rev-parse HEAD)')
        for dependency in dependencies[target]:
            dependency_body, _ = pin_body(release, dependency)
            lines += [f"ov_target_dependency {dependency} <<'{DELIMITER}'", dependency_body.rstrip("\n"), DELIMITER]
        lines += [body.rstrip("\n"), f"ov_target_build {harness}", ")"]
        blocks.append("\n".join(lines))
    return (
        "#!/bin/sh -e\n"
        f"# {GENERATED}\n"
        "#\n"
        f"# Builds the fuzz targets of {name} into $OUT, each from the pin of the release's target for it.\n"
        "# compile runs build.sh with bash; the release ran each target's build with sh -e, and so does this.\n"
        '[ -z "${BASH_VERSION:-}" ] || exec sh -e "$0"\n'
        ". /usr/local/lib/oss-verifier/release-target.sh\n\n" + "\n\n".join(blocks) + "\n"
    )


def write(directory, files, executable=("build.sh",)):
    """Write a port's files into `directory`, which must not hold any other build file."""
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.iterdir():
        if stale.name != "project.yaml":
            stale.unlink()
    for file_name, data in files.items():
        path = directory / file_name
        path.write_bytes(data if isinstance(data, bytes) else data.encode())
        path.chmod(0o755 if file_name in executable else 0o644)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("names", nargs="+", help="projects of the release to port")
    parser.add_argument("--from", dest="checkout", type=pathlib.Path, required=True,
                        help="a checkout of oss-fuzz-theorems at release 2026.10.0-rc.2")
    parser.add_argument("--recipe", type=pathlib.Path, required=True, help="that release's build recipe, unpacked")
    parser.add_argument("--assets", type=pathlib.Path, required=True, help="a directory with its -src.MANIFEST.tsv files")
    parser.add_argument("--out", type=pathlib.Path, required=True, help="write each port to OUT/<name>/")
    options = parser.parse_args()
    release = Release(options.checkout, options.recipe, options.assets)
    failed = 0
    for name in options.names:
        try:
            files, executable = plan(name, release)
        except Unsupported as error:
            print(validate.printable(f"{name}: not ported: {error}"), file=sys.stderr)
            failed += 1
            continue
        write(options.out / name, files, executable)
        print(f"{name}: {options.out / name}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
